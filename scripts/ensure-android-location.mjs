import fs from 'node:fs'

const manifestPath = 'android/app/src/main/AndroidManifest.xml'
if (!fs.existsSync(manifestPath)) throw new Error('AndroidManifest.xml was not generated by Capacitor')

let xml = fs.readFileSync(manifestPath, 'utf8')
const permissions = ['android.permission.ACCESS_COARSE_LOCATION', 'android.permission.ACCESS_FINE_LOCATION']

for (const permission of permissions) {
  const tag = '<uses-permission android:name="' + permission + '" />'
  if (!xml.includes(tag)) {
    const marker = '<application'
    const index = xml.indexOf(marker)
    if (index < 0) throw new Error('Could not find <application> in AndroidManifest.xml')
    xml = xml.slice(0, index) + tag + '\n    ' + xml.slice(index)
  }
}

fs.writeFileSync(manifestPath, xml)
console.log('Verified Android location permissions: ACCESS_FINE_LOCATION + ACCESS_COARSE_LOCATION')
